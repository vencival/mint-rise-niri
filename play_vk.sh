#!/bin/bash
# 1. Запуск монтирования в фоне с правильными флагами
~/.local/bin/vk_music_fs ~/Music/VK -o allow_other,uid=$(id -u),gid=$(id -g) &

# Ждем 2 секунды, пока FUSE поднимет структуру папок
sleep 2

# 2. Передаем команду утилите через внутренний системный вызов
# Пробуем создать виртуальную директорию лимита в обход оболочки zsh
/usr/bin/mkdir ~/Music/VK/My\ audios/1000 2>/dev/null

# Если mkdir заблокирован, заставим систему прочесть скрытый виртуальный лимит
/usr/bin/head -n 1 ~/Music/VK/My\ audios/1000/.limit 2>/dev/null

# Ждем еще секунду для прогрузки кэша аудиозаписей
sleep 1

# 3. Запускаем плеер и сразу скармливаем ему эту папку
deadbeef ~/Music/VK/My\ audios/

